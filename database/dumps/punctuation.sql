    PRIMARY
    KEY
(
    "id"
)
    );

CREATE TABLE IF NOT EXISTS "punctuation_tasks"
(
    "id"
    BIGSERIAL
    NOT
    NULL,
    "masked_text"
    TEXT
    NOT
    NULL,
    "correct_answers"
    INTEGER []
    NOT
    NULL,
    "explanations"
    JSONB
    NOT
    NULL,

    CONSTRAINT
    "punctuation_tasks_pkey"
    PRIMARY
    KEY
(
    "id"
)
    );

